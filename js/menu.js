// RENDER MODAL ITEMS
// ============================================

function renderModalItems(items) {

    if (items.length === 0) {

        modalMenuContainer.innerHTML = `
            <div class="no-dishes-found">
                <i class="fas fa-search"></i>
                <h3>No dishes found</h3>
                <p>Try searching with another dish name.</p>
            </div>
        `;

        return;
    }

    modalMenuContainer.innerHTML = items
        .map(item => createCard(item))
        .join("");
}


// ============================================
// SEARCH DISHES
// ============================================

menuSearchInput.addEventListener("input", function () {

    const searchValue = this.value
        .trim()
        .toLowerCase();

    // Empty search → saare dishes
    if (searchValue === "") {

        renderModalItems(currentModalItems);

        return;
    }

    // Search by dish name
    const filteredItems = currentModalItems.filter(item =>
        item.name.toLowerCase().includes(searchValue)
    );

    renderModalItems(filteredItems);

});


// ============================================
// CLEAR SEARCH
// ============================================

clearMenuSearch.addEventListener("click", function () {

    menuSearchInput.value = "";

    renderModalItems(currentModalItems);

    menuSearchInput.focus();

});


