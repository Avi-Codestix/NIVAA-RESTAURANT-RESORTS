const globalMenuSearch = document.getElementById("globalMenuSearch");
const clearGlobalSearch = document.getElementById("clearGlobalSearch");
const globalSearchResults = document.getElementById("globalSearchResults");


// Store all original menu sections
const originalMenuSections = document.querySelectorAll(".dishes-section");


// ============================================
// GLOBAL SEARCH
// ============================================

if (globalMenuSearch) {

    globalMenuSearch.addEventListener("input", function () {

        const searchText = this.value.trim().toLowerCase();


        // ========================================
        // EMPTY SEARCH
        // ========================================

        if (searchText === "") {

            globalSearchResults.innerHTML = "";
            globalSearchResults.style.display = "none";

            originalMenuSections.forEach(section => {
                section.style.display = "";
            });

            return;
        }


        // ========================================
        // SEARCH ALL MENU ITEMS
        // ========================================

        const results = menuItems.filter(item => {

            const dishName = item.name
                .toLowerCase();

            const category = item.category
                .toLowerCase();

            return (
                dishName.includes(searchText) ||
                category.includes(searchText)
            );

        });


        // ========================================
        // HIDE NORMAL MENU SECTIONS
        // ========================================

        originalMenuSections.forEach(section => {
            section.style.display = "none";
        });


        // ========================================
        // SHOW SEARCH RESULTS
        // ========================================

        globalSearchResults.style.display = "grid";


        if (results.length === 0) {

            globalSearchResults.innerHTML = `
                <div class="global-no-results">
                    <i class="fas fa-search"></i>

                    <h3>No dishes found</h3>

                    <p>
                        No dish found for
                        "<strong>${searchText}</strong>"
                    </p>
                </div>
            `;

            return;
        }


        // ========================================
        // CREATE RESULT CARDS
        // ========================================

        globalSearchResults.innerHTML = results
            .map(item => createCard(item))
            .join("");

    });

}


// ============================================
// CLEAR SEARCH
// ============================================

if (clearGlobalSearch) {

    clearGlobalSearch.addEventListener("click", function () {

        globalMenuSearch.value = "";

        globalSearchResults.innerHTML = "";
        globalSearchResults.style.display = "none";


        // Show original menu
        originalMenuSections.forEach(section => {
            section.style.display = "";
        });


        globalMenuSearch.focus();

    });

}


